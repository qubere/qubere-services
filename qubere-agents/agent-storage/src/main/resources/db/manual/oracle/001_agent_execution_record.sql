    agent_version varchar2(64 char),
    input_type varchar2(512 char) not null,
    input_json clob not null,
    options_json clob,
    tenant_id varchar2(128 char),
    actor_id varchar2(128 char),
    correlation_id varchar2(128 char),
    requested_at timestamp with time zone,
